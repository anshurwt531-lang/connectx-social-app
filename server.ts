import express from 'express';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';
import { GoogleGenAI, GenerateVideosOperation } from '@google/genai';
import { createServer as createViteServer } from 'vite';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT ? parseInt(process.env.PORT, 10) : 3000;

app.use(express.json({ limit: '50mb' }));
app.use(express.urlencoded({ extended: true, limit: '50mb' }));

const apiKey = process.env.GEMINI_API_KEY;

// Server-side Gemini client with recommended telemetry header
const ai = apiKey
  ? new GoogleGenAI({
      apiKey: apiKey,
      httpOptions: {
        headers: {
          'User-Agent': 'aistudio-build',
        },
      },
    })
  : null;

// Endpoint: Health & API status check
app.get('/api/status', (_req, res) => {
  res.json({
    status: 'ok',
    apiKeyConfigured: Boolean(apiKey),
    models: {
      imageModel: 'gemini-3-pro-image-preview',
      videoModel: 'veo-3.1-fast-generate-preview',
    },
  });
});

// Endpoint: Generate high quality image using gemini-3-pro-image-preview
app.post('/api/generate-image', async (req, res) => {
  try {
    if (!ai) {
      return res.status(503).json({
        error: 'GEMINI_API_KEY is not configured on the server. Please set it in Settings > Secrets.',
      });
    }

    const { prompt, aspectRatio = '1:1', imageSize = '1K' } = req.body;

    if (!prompt || typeof prompt !== 'string') {
      return res.status(400).json({ error: 'Missing or invalid prompt parameter.' });
    }

    // Supported aspect ratios: "1:1", "3:4", "4:3", "9:16", "16:9", "1:4", "1:8", "4:1", "8:1"
    const validAspectRatios = ['1:1', '3:4', '4:3', '9:16', '16:9', '1:4', '1:8', '4:1', '8:1'];
    const selectedAspectRatio = validAspectRatios.includes(aspectRatio) ? aspectRatio : '1:1';

    // Supported image sizes: "1K", "2K", "4K"
    const validSizes = ['1K', '2K', '4K'];
    const selectedSize = validSizes.includes(imageSize) ? imageSize : '1K';

    const response = await ai.models.generateContent({
      model: 'gemini-3-pro-image-preview',
      contents: {
        parts: [
          {
            text: prompt,
          },
        ],
      },
      config: {
        imageConfig: {
          aspectRatio: selectedAspectRatio,
          imageSize: selectedSize,
        },
      },
    });

    let imageUrl: string | null = null;
    let descriptionText = '';

    if (response.candidates && response.candidates[0]?.content?.parts) {
      for (const part of response.candidates[0].content.parts) {
        if (part.inlineData?.data) {
          const mime = part.inlineData.mimeType || 'image/png';
          imageUrl = `data:${mime};base64,${part.inlineData.data}`;
        } else if (part.text) {
          descriptionText += part.text;
        }
      }
    }

    if (!imageUrl) {
      return res.status(502).json({
        error: 'No image was generated by the model. Please refine your prompt.',
        description: descriptionText,
      });
    }

    return res.json({
      imageUrl,
      description: descriptionText,
      imageSize: selectedSize,
      aspectRatio: selectedAspectRatio,
    });
  } catch (error: any) {
    console.error('Error generating image:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to generate image',
    });
  }
});

// Endpoint: Generate video from photo using Veo (veo-3.1-fast-generate-preview)
app.post('/api/generate-video', async (req, res) => {
  try {
    if (!ai) {
      return res.status(503).json({
        error: 'GEMINI_API_KEY is not configured on the server. Please set it in Settings > Secrets.',
      });
    }

    const {
      prompt,
      imageBase64,
      mimeType = 'image/png',
      aspectRatio = '9:16',
      resolution = '720p',
    } = req.body;

    if (!imageBase64) {
      return res.status(400).json({ error: 'imageBase64 is required to animate an image into video.' });
    }

    // Clean base64 string if it contains data URI header
    const cleanBase64 = imageBase64.replace(/^data:image\/[a-zA-Z]+;base64,/, '');

    // Veo supports 16:9 or 9:16
    const selectedAspectRatio = aspectRatio === '16:9' ? '16:9' : '9:16';
    const selectedResolution = resolution === '1080p' ? '1080p' : '720p';

    const operation = await ai.models.generateVideos({
      model: 'veo-3.1-fast-generate-preview',
      prompt: prompt || 'Bring this logo and photo to life with smooth dynamic motion and vibrant lighting',
      image: {
        imageBytes: cleanBase64,
        mimeType: mimeType || 'image/png',
      },
      config: {
        numberOfVideos: 1,
        resolution: selectedResolution,
        aspectRatio: selectedAspectRatio,
      },
    });

    return res.json({
      operationName: operation.name,
      aspectRatio: selectedAspectRatio,
      resolution: selectedResolution,
    });
  } catch (error: any) {
    console.error('Error initiating Veo video generation:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to initiate video generation',
    });
  }
});

// Endpoint: Poll video generation status
app.post('/api/video-status', async (req, res) => {
  try {
    if (!ai) {
      return res.status(503).json({ error: 'GEMINI_API_KEY not configured.' });
    }

    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: 'Missing operationName' });
    }

    const op = new GenerateVideosOperation();
    op.name = operationName;
    const updated = await ai.operations.getVideosOperation({ operation: op });

    const isDone = Boolean(updated.done);
    const hasError = updated.error ? updated.error.message : null;

    return res.json({
      done: isDone,
      error: hasError,
      metadata: updated.metadata,
    });
  } catch (error: any) {
    console.error('Error checking video status:', error);
    return res.status(500).json({
      error: error?.message || 'Failed to check video status',
    });
  }
});

// Endpoint: Download video and stream to client
app.post('/api/video-download', async (req, res) => {
  try {
    if (!ai || !apiKey) {
      return res.status(503).json({ error: 'GEMINI_API_KEY not configured.' });
    }

    const { operationName } = req.body;
    if (!operationName) {
      return res.status(400).json({ error: 'Missing operationName' });
    }

    const op = new GenerateVideosOperation();
    op.name = operationName;
    const updated = await ai.operations.getVideosOperation({ operation: op });

    const uri = updated.response?.generatedVideos?.[0]?.video?.uri;
    if (!uri) {
      return res.status(404).json({ error: 'Generated video URI not found or video not ready yet.' });
    }

    const videoRes = await fetch(uri, {
      headers: {
        'x-goog-api-key': apiKey,
      },
    });

    if (!videoRes.ok) {
      return res.status(videoRes.status).json({
        error: `Failed to fetch video from storage: ${videoRes.statusText}`,
      });
    }

    res.setHeader('Content-Type', 'video/mp4');
    res.setHeader('Content-Disposition', 'inline; filename="connectx_animated_video.mp4"');

    if (videoRes.body) {
      await videoRes.body.pipeTo(
        new WritableStream({
          write(chunk) {
            res.write(chunk);
          },
          close() {
            res.end();
          },
          abort(err) {
            console.error('Video stream aborted:', err);
            res.destroy(err);
          },
        })
      );
    } else {
      const buffer = await videoRes.arrayBuffer();
      res.send(Buffer.from(buffer));
    }
  } catch (error: any) {
    console.error('Error downloading video:', error);
    if (!res.headersSent) {
      return res.status(500).json({
        error: error?.message || 'Failed to download generated video',
      });
    }
  }
});

// Setup Vite middleware in dev or static files in production
async function startServer() {
  if (process.env.NODE_ENV === 'production') {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  } else {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`ConnectX server running at http://0.0.0.0:${PORT}`);
  });
}

startServer().catch((err) => {
  console.error('Server failed to start:', err);
  process.exit(1);
});
